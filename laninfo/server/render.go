func newMarkdown() goldmark.Markdown {
	return goldmark.New(
		goldmark.WithExtensions(extension.GFM, extension.DefinitionList),
		goldmark.WithParserOptions(parser.WithAutoHeadingID()),
		// content is written by the organizer, so raw HTML is allowed
		goldmark.WithRendererOptions(gmhtml.WithUnsafe()),
	)
}

// markdown renders a markdown document after replacing {{vars}}.
func (a *App) markdown(src string, e expander) template.HTML {
	var buf bytes.Buffer
	if err := a.md.Convert([]byte(e.expand(src)), &buf); err != nil {
		return template.HTML("<pre>" + template.HTMLEscapeString(err.Error()) + "</pre>")
	}
	return template.HTML(callouts(buf.String()))
}

// inline renders a short markdown snippet without the wrapping <p>.
func (a *App) inline(src string, e expander) template.HTML {
	out := strings.TrimSpace(string(a.markdown(src, e)))
	if strings.HasPrefix(out, "<p>") && strings.HasSuffix(out, "</p>") && strings.Count(out, "<p>") == 1 {
		out = strings.TrimSuffix(strings.TrimPrefix(out, "<p>"), "</p>")
	}
	return template.HTML(out)
}

// GitHub style callouts: "> [!NOTE]", "> [!TIP]", "> [!WARNING]", ...
var calloutRe = regexp.MustCompile(`<blockquote>\s*<p>\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\s*`)

var calloutTitles = map[string]string{"NOTE": "Note", "TIP": "Tip", "IMPORTANT": "Important", "WARNING": "Warning", "CAUTION": "Caution"}

func callouts(html string) string {
	return calloutRe.ReplaceAllStringFunc(html, func(m string) string {
		kind := calloutRe.FindStringSubmatch(m)[1]
		return fmt.Sprintf(`<blockquote class="callout callout-%s"><p class="callout-title">%s</p><p>`,
			strings.ToLower(kind), calloutTitles[kind])
	})
}

func humanSize(n int64) string {
	const unit = 1024
	if n < unit {
		return fmt.Sprintf("%d B", n)
	}
	div, exp := int64(unit), 0
	for m := n / unit; m >= unit; m /= unit {
		div *= unit
		exp++
	}
	v := float64(n) / float64(div)
	suffix := []string{"KB", "MB", "GB", "TB", "PB"}[exp]
	if v >= 100 {
		return fmt.Sprintf("%.0f %s", v, suffix)
	}
	return fmt.Sprintf("%.1f %s", v, suffix)
}

var templateFuncs = template.FuncMap{
	"icon":  icon,
	"size":  humanSize,
	"date":  func(t time.Time) string { return t.Format("2006-01-02 15:04") },
	"lower": strings.ToLower,
	"join":  strings.Join,
	"plural": func(n int, one, many string) string {
		if n == 1 {
			return one
		}
		return many
	},
}

